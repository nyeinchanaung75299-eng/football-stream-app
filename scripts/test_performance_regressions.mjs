// Lightweight performance-safety regression guard. Run with Node 22+.
// This complements (but does not replace) Flutter and real-device tests.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

const read = (name) => readFileSync(new URL('../' + name, import.meta.url), 'utf8');
const web = read('user_app/web/index.html');
const embedded = read('user_app/assets/embedded_player.html');
const home = read('user_app/lib/screens/home_page.dart');
const sources = read('user_app/lib/screens/source_browser_page.dart');
const maintenance = read('supabase/functions/football-score-sync/index.ts');

function compileInlineScripts(html, name) {
  const scriptTag = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;
  let count = 0;
  for (const match of html.matchAll(scriptTag)) {
    if (/\bsrc\s*=/.test(match[1])) continue;
    if (!match[2].trim()) continue;
    new vm.Script(match[2], { filename: name + ':inline-' + (++count) });
  }
  assert.ok(count > 0, name + ' must contain compiled scripts');
}
compileInlineScripts(web, 'viewer-web');
compileInlineScripts(embedded, 'embedded-player');

// Shared player must stay byte-identical to the source HTML generator.
const style = web.match(/<style>[\s\S]*?<\/style>/)?.[0];
const playerStyle = web.match(/<style id="nca-reference-player-style">[\s\S]*?<\/style>/)?.[0];
const body = web.match(/<body>\s*([\s\S]*?)\s*<script src="flutter_bootstrap\.js"[^>]*><\/script>/)?.[1];
assert.ok(style && playerStyle && body, 'shared player extraction markers');
const playerBody = body.replace(/<!-- Web shell start -->[\s\S]*?<!-- Web shell end -->/g, '').trim();
const generated = '<!DOCTYPE html>\n<!-- Generated by scripts/generate_embedded_player.py. -->\n' +
  '<html><head><meta charset="UTF-8">\n' +
  '<meta name="viewport" content="width=device-width, initial-scale=1.0">\n' +
  '<meta name="referrer" content="no-referrer">\n' +
  '<title>NCA Player</title>\n' + style + '\n' + playerStyle +
  '\n</head>\n<body>\n' + playerBody + '\n</body>\n</html>\n';
assert.equal(embedded, generated, 'native shared Web player must remain in sync');

assert.match(home, /\.take\(2\)/, 'do not increase speculative stream lookups');
assert.match(home, /_openingPlayer\) return;/, 'do not prefetch while opening player');
assert.doesNotMatch(sources, /_recentSourceLists/,
  'source matches must remain authoritative after successful empty refresh');
assert.match(home, /_streamWarmup\?\.cancel\(\)/,
  'cancel delayed metadata prefetch on dispose');
// During the playback rollback trial use the last pre-#106 streaming script.
// Keep source/security and fallback assertions even while milestone telemetry
// from #106 is intentionally not included in this version.
assert.match(web, /function sourceSupport\(source\)/,
  'platform-specific source selection must remain guarded');
assert.match(web, /playback line failed/,
  'failed lines must still reach the fallback system');
assert.match(web, /shaka\.Player\.isBrowserSupported\(\)/,
  'browser capability checks must remain present');
assert.match(home, /watchToSourcesClock/,
  'retain source discovery instrumentation outside the rolled-back player');
assert.match(home, /chooser_ms/,
  'retain human line-selection timing');
assert.match(maintenance, /15 \* 60 \* 1000/, 'avoid repeat probes within 15 minutes');
assert.match(maintenance, /\.limit\(12\)/, 'cap routine probe batches');
assert.match(maintenance, /hideStaleMatches\(client, now\)/);
assert.match(maintenance, /disableExpiredStreams\(client, now\)/);

console.log('NCA performance regression guards passed.');
