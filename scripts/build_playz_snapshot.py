"""Build the checked-in PlayZ catalog fixture from an authorized local decode.

The decoder output is intentionally not shipped. The runtime catalog contains
only visible entries and direct HTTPS media URLs that do not require a token or
DRM key. This keeps credentials out of source control and out of Admin builds.
"""

import json
import pathlib
import re
import argparse


ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "supabase/functions/_shared/playz_snapshot.mjs"


def media_type(url):
    path = url.lower().split("?", 1)[0]
    if ".m3u8" in path or "/hls/" in path:
        return "hls"
    if ".mpd" in path or "/dash/" in path:
        return "dash"
    if ".flv" in path:
        return "flv"
    if ".mp4" in path:
        return "mp4"
    return "auto"


def clean_line(row):
    if row.get("api") or row.get("tokenApi"):
        return None
    raw = str(row.get("link", "")).strip()
    if not raw.startswith("https://"):
        return None
    parts = raw.split("|")
    url = parts[0].strip()
    if not url or "localhost" in url:
        return None
    headers = {}
    for item in parts[1:]:
        if "=" in item:
            key, value = item.split("=", 1)
            headers[key.strip().lower()] = value.strip()
    referer = headers.get("referer") or headers.get("referrer")
    origin = headers.get("origin")
    return {
        "label": str(row.get("name") or "PlayZ stream").strip(),
        "url": url,
        "stream_type": media_type(url),
        "resolution": "Auto",
        "referer": referer,
        "origin": origin,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("decoded_channels", type=pathlib.Path)
    parser.add_argument("events", type=pathlib.Path)
    parser.add_argument("event_lines", type=pathlib.Path)
    args = parser.parse_args()
    catalog = json.loads((args.decoded_channels / "catalog.json").read_text())
    channels = []
    for index, item in enumerate(catalog):
        if item.get("visible") is not True:
            continue
        try:
            decoded = json.loads((args.decoded_channels / f"{index:03d}.json").read_text())
        except (FileNotFoundError, json.JSONDecodeError):
            continue
        lines = [line for row in decoded if (line := clean_line(row))]
        if not lines:
            continue
        channels.append({
            "id": f"channel:{index}",
            "name": re.sub(r"\s+", " ", str(item.get("name", "Sports channel"))).strip(),
            "logo": item.get("logo"),
            "lines": lines,
        })

    events = []
    event_rows = json.loads(args.events.read_text())
    decoded_lines = json.loads(args.event_lines.read_text())
    first = event_rows[0]
    lines = [line for row in decoded_lines if (line := clean_line(row))]
    if first.get("visible") is True and lines:
        events.append({
            "id": "event:premier-league-liverpool-manchester-city",
            "league": first.get("eventName") or "Football",
            "home": first.get("teamAName") or "Home",
            "away": first.get("teamBName") or "Away",
            "home_logo": first.get("teamAFlag"),
            "away_logo": first.get("teamBFlag"),
            "date": first.get("date"),
            "time": first.get("time"),
            "lines": lines,
        })

    payload = {"version": 1, "channels": channels, "events": events}
    OUTPUT.write_text(
        "// Generated by scripts/build_playz_snapshot.py. Direct, keyless HTTPS media only.\n"
        "export const playzSnapshot = "
        + json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
        + ";\n"
    )
    print(f"wrote {len(channels)} channels and {len(events)} events to {OUTPUT}")


if __name__ == "__main__":
    main()
